#!/usr/bin/env bash
# Builds single-file copies in dist/ for pasting into the Apps Script editor.
#   dist/Lodestone.gs   core, all files in one
#   dist/DeviceImport.gs  optional module
#   dist/appsscript.json  manifest
# Edit src/, not dist/. Run from anywhere.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p dist
{
  echo "// Lodestone core. Generated by tools/bundle.sh. Edit src/core, not this file."
  for f in Config Logic Forms Sheet Refresh Setup Summary; do
    echo
    echo "// ---- $f.gs ----"
    cat "src/core/$f.gs"
  done
} > dist/Lodestone.gs
cp src/modules/device-import/DeviceImport.gs dist/DeviceImport.gs
cp src/appsscript.json dist/appsscript.json
echo "dist/ rebuilt."
